package com.mycompany.finalprojectveyerusjustin;

public class Food {
    private double x;
    private double y;
    private double value;

    public Food(double x, double y, double value) {
        this.x = x;
        this.y = y;
        this.value = value;
    }

    public double getX() { return x; }
    public double getY() { return y; }
    public double getValue() { return value; }
}